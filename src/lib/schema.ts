/**
 * Сериализация JSON-LD для вставки в <script type="application/ld+json">.
 *
 * Экранируем «<»: если в разметку попадает код виджета со строкой
 * "</script>" (а он попадает — например, в HowTo про установку на сайт),
 * браузер и краулеры обрывают блок на этом месте, и вся схема страницы
 * теряется. Внутри JSON-строки \u003c читается как «<», поэтому смысл
 * данных не меняется.
 *
 * Неразрывные пробелы и дефисы заменяем обычными: они нужны только для вёрстки.
 */
export function jsonLdScript(data: unknown): string {
  return (
    JSON.stringify(data)
      .replace(/</g, "\\u003c")
      // В видимых текстах «Навылет! AI» и цены пишутся с неразрывным
      // пробелом (чтобы не переносились), а в разметке нужен обычный.
      .replace(/\u00a0/g, " ")
      .replace(/\u2011/g, "-")
  );
}
